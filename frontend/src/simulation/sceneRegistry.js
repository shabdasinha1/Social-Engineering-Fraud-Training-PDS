/** Scenario ids with an authored scene in this build. Used by the guard tests. */
export const AUTHORED_SCENARIO_IDS = Object.keys(BUILDERS)

/**
 * The scene for a scenario payload, or null when it has none.
 *
 * Built from the payload on every call rather than memoised: the scenario object is
 * itself server state that the controller replaces whenever the engine answers, and a
 * cached scene keyed on a scenario id would be a second, staler copy of it.
 */
export function sceneFor(scenario) {
  const build = BUILDERS[scenario?.scenario_id]
  if (!build) return null
  const scene = build(scenario)
  // A pack built for a different platform than the run is a programming error, not a
  // rendering decision: fall back rather than draw WhatsApp chrome around an email.
  if (scene.platform !== scenario.platform) return null
  return scene
}
